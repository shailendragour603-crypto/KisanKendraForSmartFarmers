def main():
    print(f"Preparing to upload {len(NEW_TRANSLATIONS)} translations to Firebase...")

    # 1. Connect to Firebase
    if not os.path.exists('serviceAccountKey.json'):
        print("Error: serviceAccountKey.json not found in this folder!")
        return

    cred = credentials.Certificate('serviceAccountKey.json')
    if not firebase_admin._apps:
        firebase_admin.initialize_app(cred)

    db = firestore.client()
    doc_ref = db.collection('app_translations').document('hi')

    # 2. Prepare the batch update using dot-notation (so we don't delete existing words!)
    updates = {}
    for english_word, hindi_word in NEW_TRANSLATIONS.items():
        # Clean the key (lowercase, strip spaces)
        clean_key = english_word.lower().strip()
        updates[f"dictionary.{clean_key}"] = hindi_word.strip()

    # 3. Push to Firebase
    try:
        doc_ref.update(updates)
        print("✅ SUCCESS! All translations safely merged into Firebase.")
        print("Your Admin Panel in the app will now show these new words.")
    except Exception as e:
        # If the document doesn't exist yet, we create it
        if "NOT_FOUND" in str(e):
             doc_ref.set({"dictionary": NEW_TRANSLATIONS})
             print("✅ SUCCESS! Created new dictionary in Firebase.")
        else:
             print(f"❌ Error uploading to Firebase: {e}")

if __name__ == "__main__":
    main()
